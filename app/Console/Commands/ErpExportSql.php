<?php

namespace App\Console\Commands;

use App\Erp\Db;
use Illuminate\Console\Command;
use PDO;

/**
 * Writes database.sql: the complete schema (all tables, keys, indexes, foreign keys) plus the default data
 * of a fresh install (roles, permissions, chart of accounts, expense categories …) and the migration records,
 * for importing with phpMyAdmin. Run it against a freshly migrated + `erp:install`ed database.
 * Never exported: user accounts, sessions, logs, queue jobs, and `settings` (holds per-install generated keys).
 */
class ErpExportSql extends Command
{
    protected $signature = 'erp:export-sql {--output=database.sql : file to write}';

    protected $description = 'Write database.sql (schema + default data, no users or secrets) for phpMyAdmin import';

    /** tables whose rows are never exported */
    private const NO_DATA = ['users', 'sessions', 'password_reset_tokens', 'cache', 'cache_locks', 'jobs', 'job_batches', 'failed_jobs', 'settings',
        'events', 'sync_log', 'webhook_events', 'sync_runs', 'shopify_writes', 'sync_issues', 'files', 'user_permissions'];

    public function handle(): int
    {
        $pdo = Db::pdo();
        $db = (string) Db::val('SELECT DATABASE()');
        $tables = array_map(fn ($r) => array_values($r)[0], Db::all('SHOW FULL TABLES WHERE Table_type = \'BASE TABLE\''));
        sort($tables);
        $version = (string) Db::val('SELECT VERSION()');
        $out = [];
        $out[] = '-- SundayBazar ERP — database schema and default data';
        $out[] = '-- Generated by `php artisan erp:export-sql` on '.gmdate('Y-m-d H:i').' UTC from a fresh install ('.$version.').';
        $out[] = '--';
        $out[] = '-- Import with phpMyAdmin: create the database (utf8mb4_unicode_ci), select it, Import -> this file.';
        $out[] = '-- Safe to import again: tables are created only if missing and default rows are inserted only if missing.';
        $out[] = '-- Contains NO user accounts and NO passwords. Create the first administrator afterwards with';
        $out[] = '--   php artisan erp:admin <username> --email=<you@example.com>';
        $out[] = '-- Engine InnoDB, character set utf8mb4. Works on MySQL 8+ and MariaDB 10.4+.';
        $out[] = '';
        $out[] = 'SET NAMES utf8mb4;';
        $out[] = "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';";
        $out[] = 'SET time_zone = \'+00:00\';';
        $out[] = 'SET FOREIGN_KEY_CHECKS = 0;';
        $out[] = 'START TRANSACTION;';
        $out[] = '';
        $rowsTotal = 0;
        foreach ($tables as $t) {
            $create = array_values(Db::get("SHOW CREATE TABLE `{$t}`"))[1];
            $create = preg_replace('/^CREATE TABLE /', 'CREATE TABLE IF NOT EXISTS ', $create);
            $create = preg_replace('/ AUTO_INCREMENT=\d+/', '', $create);
            $out[] = '-- ------------------------------------------------------------ '.$t;
            $out[] = $create.';';
            if (! in_array($t, self::NO_DATA, true)) {
                $st = $pdo->query("SELECT * FROM `{$t}`");
                $rows = $st->fetchAll(PDO::FETCH_ASSOC);
                if ($rows) {
                    $cols = '`'.implode('`,`', array_keys($rows[0])).'`';
                    foreach (array_chunk($rows, 100) as $chunk) {
                        $vals = array_map(fn ($r) => '('.implode(',', array_map(fn ($v) => $v === null ? 'NULL' : (is_int($v) || is_float($v) ? (string) $v : $pdo->quote((string) $v)), $r)).')', $chunk);
                        $out[] = "INSERT IGNORE INTO `{$t}` ({$cols}) VALUES\n".implode(",\n", $vals).';';
                    }
                    $rowsTotal += count($rows);
                }
            }
            $out[] = '';
        }
        $out[] = 'SET FOREIGN_KEY_CHECKS = 1;';
        $out[] = 'COMMIT;';
        $file = base_path($this->option('output'));
        file_put_contents($file, implode("\n", $out)."\n");
        $this->info(count($tables)." tables, {$rowsTotal} default rows -> {$file} (from database {$db})");
        return self::SUCCESS;
    }
}
